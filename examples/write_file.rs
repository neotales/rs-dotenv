//! Writes a generated dotenv document to a file under the temp directory.
//!
//! Run with `cargo run --example write_file`. The output directory is `TMPDIR` when it is set,
//! and the system temp directory otherwise.

use std::env;
use std::error::Error;
use std::path::PathBuf;

use neotales_dotenv::Document;

fn main() -> Result<(), Box<dyn Error>> {
    let mut document = Document::new();
    document.add_comment("generated by the write_file example");
    document.add_variable("APP_NAME", "neotales");
    document.set("DEBUG", "false");
    document.add_inline_comment("written once, by hand");

    let directory = env::var_os("TMPDIR").map_or_else(env::temp_dir, PathBuf::from);
    let path = directory.join("neotales-dotenv-example.env");
    std::fs::write(&path, document.to_string())?;

    println!("wrote {}", path.display());
    println!("{document}");
    Ok(())
}
